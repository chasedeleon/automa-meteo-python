"""Scrive storia/chat.md con tutti i commenti già esistenti delle Pull Request e Issue di un deposito."""
import json, subprocess, sys
from datetime import datetime
from zoneinfo import ZoneInfo
repo, out = sys.argv[1], sys.argv[2]
cm = json.loads(subprocess.check_output(["gh", "api", f"repos/{repo}/issues/comments?per_page=100&sort=created&direction=asc"]))
titoli = {}
r = ["# La chat del progetto\n\nOgni messaggio scritto su GitHub (Pull Request e Issue), in ordine di arrivo. Si aggiunge da solo.\n"]
for c in cm:
    n = int(c["issue_url"].rsplit("/", 1)[1])
    if n not in titoli:
        titoli[n] = json.loads(subprocess.check_output(["gh", "api", f"repos/{repo}/issues/{n}"]))["title"]
    q = datetime.fromisoformat(c["created_at"].replace("Z", "+00:00")).astimezone(ZoneInfo("Europe/Rome"))
    chi = c["user"]["login"]
    if "Generated by [Claude Code]" in c["body"]:
        chi = "Claude (dall'account " + chi + ")"
    r.append(f"\n## {q:%d/%m/%Y %H:%M} · {chi} · #{n} {titoli[n]}\n\n{c['body'].replace(chr(13), '').strip()}\n")
open(out, "w", encoding="utf-8").write("".join(r))
print(repo, len(cm), "messaggi")
